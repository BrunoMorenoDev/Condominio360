-- =====================================================================
-- Condominio360 · 01_esquema.sql
-- Tablas del Diagrama Entidad-Relación (Documento de Especificación
-- Funcional, sección 4). Motor: PostgreSQL 17 (Supabase).
--
-- Convenciones:
--   * Nombres en snake_case, igual que en el diagrama.
--   * Claves primarias INTEGER autoincrementales (identity).
--   * Los dominios de estado / tipo / método se controlan con CHECK.
--   * Las claves foráneas usan ON DELETE RESTRICT: no se borra un
--     registro que tiene información dependiente (historial de cobro).
-- =====================================================================

-- ---------------------------------------------------------------------
-- roles
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(20)  NOT NULL,
    descripcion VARCHAR(150),
    CONSTRAINT uq_roles_nombre UNIQUE (nombre)
);

-- ---------------------------------------------------------------------
-- unidades
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.unidades (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torre     VARCHAR(20)   NOT NULL,
    numero    VARCHAR(10)   NOT NULL,
    piso      INTEGER       NOT NULL,
    tipo      VARCHAR(20)   NOT NULL,
    area_m2   DECIMAL(8,2)  NOT NULL,
    alicuota  DECIMAL(10,2) NOT NULL,
    activa    BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_unidades_torre_numero UNIQUE (torre, numero),
    CONSTRAINT ck_unidades_piso      CHECK (piso BETWEEN 0 AND 60),
    CONSTRAINT ck_unidades_tipo      CHECK (tipo IN ('Departamento','Casa','Local','Oficina')),
    CONSTRAINT ck_unidades_area      CHECK (area_m2 > 0),
    CONSTRAINT ck_unidades_alicuota  CHECK (alicuota >= 0)
);

-- ---------------------------------------------------------------------
-- residentes
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.residentes (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres          VARCHAR(60)  NOT NULL,
    apellidos        VARCHAR(60)  NOT NULL,
    cedula           CHAR(10)     NOT NULL,
    correo           VARCHAR(100) NOT NULL,
    telefono         VARCHAR(15),
    tipo             VARCHAR(20)  NOT NULL,
    fecha_ingreso    DATE         NOT NULL,
    responsable_pago BOOLEAN      NOT NULL DEFAULT FALSE,
    unidad_id        INTEGER      NOT NULL,
    CONSTRAINT uq_residentes_cedula UNIQUE (cedula),
    CONSTRAINT ck_residentes_cedula CHECK (cedula ~ '^[0-9]{10}$'),
    CONSTRAINT ck_residentes_tipo   CHECK (tipo IN ('Propietario','Arrendatario')),
    CONSTRAINT fk_residentes_unidad FOREIGN KEY (unidad_id)
        REFERENCES public.unidades (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_residentes_unidad_id ON public.residentes (unidad_id);
-- Solo un responsable de pago por unidad
CREATE UNIQUE INDEX IF NOT EXISTS uq_residentes_responsable_por_unidad
    ON public.residentes (unidad_id) WHERE responsable_pago;

-- ---------------------------------------------------------------------
-- usuarios
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuarios (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario  VARCHAR(50)  NOT NULL,
    password_hash   TEXT         NOT NULL,
    nombre_completo VARCHAR(100) NOT NULL,
    correo          VARCHAR(100) NOT NULL,
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en       TIMESTAMP    NOT NULL DEFAULT now(),
    rol_id          INTEGER      NOT NULL,
    residente_id    INTEGER,
    CONSTRAINT uq_usuarios_nombre_usuario UNIQUE (nombre_usuario),
    CONSTRAINT uq_usuarios_residente      UNIQUE (residente_id),
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (rol_id)
        REFERENCES public.roles (id) ON DELETE RESTRICT,
    CONSTRAINT fk_usuarios_residente FOREIGN KEY (residente_id)
        REFERENCES public.residentes (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_usuarios_rol_id ON public.usuarios (rol_id);

-- ---------------------------------------------------------------------
-- configuracion_cobro  (parámetros D, G y t del Core)
-- La configuración vigente es la de mayor vigente_desde <= fecha de corte.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.configuracion_cobro (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_vencimiento       INTEGER      NOT NULL,
    dias_gracia           INTEGER      NOT NULL,
    tasa_recargo_mensual  DECIMAL(5,4) NOT NULL,
    vigente_desde         DATE         NOT NULL,
    actualizado_por       INTEGER      NOT NULL,
    CONSTRAINT uq_configuracion_vigente_desde UNIQUE (vigente_desde),
    CONSTRAINT ck_configuracion_dia   CHECK (dia_vencimiento BETWEEN 1 AND 28),
    CONSTRAINT ck_configuracion_gracia CHECK (dias_gracia BETWEEN 0 AND 30),
    CONSTRAINT ck_configuracion_tasa  CHECK (tasa_recargo_mensual >= 0 AND tasa_recargo_mensual <= 0.1000),
    CONSTRAINT fk_configuracion_usuario FOREIGN KEY (actualizado_por)
        REFERENCES public.usuarios (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_configuracion_actualizado_por ON public.configuracion_cobro (actualizado_por);

-- ---------------------------------------------------------------------
-- cuotas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cuotas (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidad_id         INTEGER       NOT NULL,
    anio              INTEGER       NOT NULL,
    mes               INTEGER       NOT NULL,
    monto             DECIMAL(10,2) NOT NULL,
    capital_pagado    DECIMAL(10,2) NOT NULL DEFAULT 0,
    recargo_pagado    DECIMAL(10,2) NOT NULL DEFAULT 0,
    fecha_emision     DATE          NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    estado            VARCHAR(15)   NOT NULL DEFAULT 'Pendiente',
    generada_por      INTEGER       NOT NULL,
    CONSTRAINT uq_cuotas_unidad_anio_mes UNIQUE (unidad_id, anio, mes),
    CONSTRAINT ck_cuotas_mes      CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT ck_cuotas_anio     CHECK (anio BETWEEN 2000 AND 2100),
    CONSTRAINT ck_cuotas_monto    CHECK (monto >= 0),
    CONSTRAINT ck_cuotas_capital  CHECK (capital_pagado >= 0 AND capital_pagado <= monto),
    CONSTRAINT ck_cuotas_recargo  CHECK (recargo_pagado >= 0),
    CONSTRAINT ck_cuotas_fechas   CHECK (fecha_vencimiento >= fecha_emision),
    CONSTRAINT ck_cuotas_estado   CHECK (estado IN ('Pendiente','Parcial','Pagada','Vencida','Anulada')),
    CONSTRAINT fk_cuotas_unidad FOREIGN KEY (unidad_id)
        REFERENCES public.unidades (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cuotas_generada_por FOREIGN KEY (generada_por)
        REFERENCES public.usuarios (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_cuotas_generada_por ON public.cuotas (generada_por);
CREATE INDEX IF NOT EXISTS ix_cuotas_periodo      ON public.cuotas (anio, mes);

-- ---------------------------------------------------------------------
-- pagos
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pagos (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidad_id          INTEGER       NOT NULL,
    residente_id       INTEGER,
    registrado_por     INTEGER       NOT NULL,
    verificado_por     INTEGER,
    fecha_pago         DATE          NOT NULL,
    monto              DECIMAL(10,2) NOT NULL,
    metodo             VARCHAR(20)   NOT NULL,
    referencia         VARCHAR(40),
    comprobante        VARCHAR(255),
    estado             VARCHAR(15)   NOT NULL DEFAULT 'PorVerificar',
    fecha_verificacion TIMESTAMP,
    observacion        VARCHAR(250),
    CONSTRAINT ck_pagos_monto  CHECK (monto > 0),
    CONSTRAINT ck_pagos_metodo CHECK (metodo IN ('Efectivo','Transferencia','Deposito')),
    CONSTRAINT ck_pagos_estado CHECK (estado IN ('PorVerificar','Verificado','Rechazado')),
    -- Transferencias y depósitos deben llevar referencia bancaria
    CONSTRAINT ck_pagos_referencia CHECK (metodo = 'Efectivo' OR referencia IS NOT NULL),
    -- Un pago rechazado debe registrar el motivo
    CONSTRAINT ck_pagos_rechazo CHECK (estado <> 'Rechazado' OR observacion IS NOT NULL),
    CONSTRAINT fk_pagos_unidad FOREIGN KEY (unidad_id)
        REFERENCES public.unidades (id) ON DELETE RESTRICT,
    CONSTRAINT fk_pagos_residente FOREIGN KEY (residente_id)
        REFERENCES public.residentes (id) ON DELETE SET NULL,
    CONSTRAINT fk_pagos_registrado_por FOREIGN KEY (registrado_por)
        REFERENCES public.usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_pagos_verificado_por FOREIGN KEY (verificado_por)
        REFERENCES public.usuarios (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_pagos_unidad_id      ON public.pagos (unidad_id);
CREATE INDEX IF NOT EXISTS ix_pagos_residente_id   ON public.pagos (residente_id);
CREATE INDEX IF NOT EXISTS ix_pagos_registrado_por ON public.pagos (registrado_por);
CREATE INDEX IF NOT EXISTS ix_pagos_verificado_por ON public.pagos (verificado_por);
CREATE INDEX IF NOT EXISTS ix_pagos_estado         ON public.pagos (estado);
-- Una misma referencia bancaria no puede registrarse dos veces (pagos no rechazados)
CREATE UNIQUE INDEX IF NOT EXISTS uq_pagos_metodo_referencia
    ON public.pagos (metodo, referencia)
    WHERE referencia IS NOT NULL AND estado <> 'Rechazado';

-- ---------------------------------------------------------------------
-- aplicaciones_pago  (distribución de un pago entre cuotas)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.aplicaciones_pago (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id       INTEGER       NOT NULL,
    cuota_id      INTEGER       NOT NULL,
    monto_recargo DECIMAL(10,2) NOT NULL DEFAULT 0,
    monto_capital DECIMAL(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_aplicaciones_montos CHECK (monto_recargo >= 0 AND monto_capital >= 0
                                             AND monto_recargo + monto_capital > 0),
    CONSTRAINT fk_aplicaciones_pago FOREIGN KEY (pago_id)
        REFERENCES public.pagos (id) ON DELETE CASCADE,
    CONSTRAINT fk_aplicaciones_cuota FOREIGN KEY (cuota_id)
        REFERENCES public.cuotas (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_aplicaciones_pago_id  ON public.aplicaciones_pago (pago_id);
CREATE INDEX IF NOT EXISTS ix_aplicaciones_cuota_id ON public.aplicaciones_pago (cuota_id);

-- ---------------------------------------------------------------------
-- areas_comunales
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.areas_comunales (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(60)  NOT NULL,
    descripcion   VARCHAR(250),
    capacidad     INTEGER      NOT NULL,
    hora_apertura TIME         NOT NULL,
    hora_cierre   TIME         NOT NULL,
    costo_uso     DECIMAL(8,2) NOT NULL DEFAULT 0,
    activa        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_areas_nombre    UNIQUE (nombre),
    CONSTRAINT ck_areas_capacidad CHECK (capacidad > 0),
    CONSTRAINT ck_areas_horario   CHECK (hora_cierre > hora_apertura),
    CONSTRAINT ck_areas_costo     CHECK (costo_uso >= 0)
);

-- ---------------------------------------------------------------------
-- reservas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.reservas (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id      INTEGER     NOT NULL,
    residente_id INTEGER     NOT NULL,
    fecha        DATE        NOT NULL,
    hora_inicio  TIME        NOT NULL,
    hora_fin     TIME        NOT NULL,
    estado       VARCHAR(15) NOT NULL DEFAULT 'Solicitada',
    aprobada_por INTEGER,
    CONSTRAINT ck_reservas_horario CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_reservas_estado  CHECK (estado IN ('Solicitada','Aprobada','Rechazada','Cancelada')),
    CONSTRAINT fk_reservas_area FOREIGN KEY (area_id)
        REFERENCES public.areas_comunales (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservas_residente FOREIGN KEY (residente_id)
        REFERENCES public.residentes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservas_aprobada_por FOREIGN KEY (aprobada_por)
        REFERENCES public.usuarios (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_reservas_area_fecha   ON public.reservas (area_id, fecha);
CREATE INDEX IF NOT EXISTS ix_reservas_residente_id ON public.reservas (residente_id);
CREATE INDEX IF NOT EXISTS ix_reservas_aprobada_por ON public.reservas (aprobada_por);

-- ---------------------------------------------------------------------
-- visitas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.visitas (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidad_id        INTEGER      NOT NULL,
    autorizada_por   INTEGER      NOT NULL,
    registrada_por   INTEGER,
    nombre_visitante VARCHAR(100) NOT NULL,
    cedula_visitante VARCHAR(13)  NOT NULL,
    placa_vehiculo   VARCHAR(10),
    fecha_esperada   DATE         NOT NULL,
    hora_ingreso     TIMESTAMP,
    hora_salida      TIMESTAMP,
    estado           VARCHAR(15)  NOT NULL DEFAULT 'Autorizada',
    CONSTRAINT ck_visitas_estado CHECK (estado IN ('Autorizada','Ingresada','Finalizada','Cancelada')),
    CONSTRAINT ck_visitas_horas  CHECK (hora_salida IS NULL OR hora_ingreso IS NULL OR hora_salida >= hora_ingreso),
    CONSTRAINT fk_visitas_unidad FOREIGN KEY (unidad_id)
        REFERENCES public.unidades (id) ON DELETE RESTRICT,
    CONSTRAINT fk_visitas_autorizada_por FOREIGN KEY (autorizada_por)
        REFERENCES public.residentes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_visitas_registrada_por FOREIGN KEY (registrada_por)
        REFERENCES public.usuarios (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_visitas_unidad_id      ON public.visitas (unidad_id);
CREATE INDEX IF NOT EXISTS ix_visitas_autorizada_por ON public.visitas (autorizada_por);
CREATE INDEX IF NOT EXISTS ix_visitas_registrada_por ON public.visitas (registrada_por);
CREATE INDEX IF NOT EXISTS ix_visitas_fecha_esperada ON public.visitas (fecha_esperada);
